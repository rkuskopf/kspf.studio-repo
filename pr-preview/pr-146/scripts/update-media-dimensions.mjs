#!/usr/bin/env node
// Cache metadata only, without downloading every full slide in the browser.
// Pass checked-in and/or freshly fetched projects JSON paths; no CMS writes.
// node scripts/update-media-dimensions.mjs projects.json /tmp/draft-projects.json
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const inputs = process.argv.slice(2);
const sources = new Set();
for (const input of inputs.length ? inputs : ['projects.json']) {
  const json = JSON.parse(await readFile(input, 'utf8'));
  for (const project of Array.isArray(json) ? json : json.projects || []) {
    for (const src of project.slides || []) sources.add(src);
  }
}
const output = fileURLToPath(new URL('../assets/media-dimensions.js', import.meta.url));
const existing = await readFile(output, 'utf8').catch(() => '');
const cache = existing ? JSON.parse(existing.slice(existing.indexOf('{'), existing.lastIndexOf('}') + 1)) : {};
const results = await Promise.allSettled([...sources].map(async src => {
  // Storyblok images encode their dimensions. Unknown sources use stable fallback.
  if (!/^https:\/\/res\.cloudinary\.com\/[^/]+\/(?:image|video)\/upload\/v\d+\//.test(src)) return;
  const response = await fetch(src, { method: 'HEAD', signal: AbortSignal.timeout(15000) });
  if (!response.ok) throw new Error(`Metadata HTTP ${response.status}: ${src}`);
  const timing = response.headers.get('server-timing') || '';
  const width = Number(/(?:^|[,;"])width=(\d+)/.exec(timing)?.[1]);
  const height = Number(/(?:^|[,;"])height=(\d+)/.exec(timing)?.[1]);
  if (width && height) cache[src] = [width, height];
  else throw new Error(`No dimensions returned: ${src}`);
}));
for (const result of results) if (result.status === 'rejected') console.warn(result.reason.message);
await writeFile(output, '// Generated by scripts/update-media-dimensions.mjs from delivery metadata.\n' +
  'window.kspfMediaDimensions = ' + JSON.stringify(Object.fromEntries(Object.entries(cache).sort()), null, 2) + ';\n');
console.log(`Cached dimensions for ${Object.keys(cache).length} sources.`);
